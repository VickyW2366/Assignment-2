  <h1>The different statuses of the buses explained</h1>
  <p>Listed alongside other information is the status of a bus, which will be either Currently running, 
    Maintenance needed, In storage, On loan, or Dilapidated. Below all the meanings of the different 
    statuses are listed.</p>

<div>
  <h2>Currently running</h2>
  <p>This bus has no major faults and has been found safe to be used by the public, any bus with this 
    status has a chance to be used during open days.</p>
</div>
<div>
  <h2>Maintenance needed</h2>
  <p>This bus needs some minor repairs like some fresh oil or water leakage, but soon this bus will be 
    good to run on open days.</p>
</div><div>
  <h2>In storage</h2>
  <p>This bus needs some major restoration work done, and is waiting for its turn in the workshop. 
    However it might be a year or more before this bus could be used during an open day.</p>
</div><div>
  <h2>On loan</h2>
  <p>This bus is temporarily being stored elsewhere whilst undergoing restoration work, or for a 
    special event.</p>
</div><div>
  <h2>Dilapidated</h2>
  <p>This bus is not likely to ever be fully restored, and is only be able to be viewed as a static exhibit.</p>
</div>


</x-layout>